"""Interference report generator (Step 7). Plain python, no FreeCAD: python build_parts/assemble_report.py
Reads results/probes/pose_<P>_<tag>.json (written by tests/probes/probe_poses.py) and ws<n>.json (probe_ws.py), and writes
research/quinn/cr_scratch/step7_interference_report.md. Every cell is a probe value; verdicts come from gates.pair_violations (ASSEMBLY.md classes and gaps).
Sections: one '## Size <tag>' per collet size (45 part pairs + 6 feature pairs for R, Kd1, Kmax), then the clamp range (T4, T5 at the two extreme
sizes) and the wrong-state table. The file is tool output; edit this script, not the report."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tests", "probes"))
import common  # noqa: E402
import gates  # noqa: E402

PROBES = os.path.join(ROOT, "results", "probes")
REPORT = os.path.join(ROOT, "research", "quinn", "cr_scratch", "step7_interference_report.md")
POSES = ("R", "Kd1", "Kmax")


def tag(d):
    whole = int(d + 1e-9)
    return "%03dp%d" % (whole, int(round((d - whole) * 10)))


def load(name):
    path = os.path.join(PROBES, name + ".json")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    p = common.load_params()
    G = lambda k: common.get(p, k)
    rels, feats = gates.parse_assembly()
    T = gates.thresholds(G, rels, feats)
    fam = list(G("core.diameters"))
    lines = ["# Step 7 interference report", "", "Generated by build_parts/assemble_report.py from results/probes/pose_*.json and ws*.json. Do not edit by hand.",
             "Columns: overlap mm3 (common volume; `-` for feature pairs), dist_mm (min distance, or the feature gap), class (ASSEMBLY.md C / G / F / P for the pose), result.", ""]
    totals = {"pairs": 0, "fail": 0}
    for d in fam:
        t = tag(d)
        probes = {pose: load("pose_%s_%s" % (pose, t)) for pose in POSES}
        lines += ["## Size %s" % t, ""]
        if any(v is None for v in probes.values()):
            lines += ["No probe JSON for poses %s." % ", ".join(k for k, v in probes.items() if v is None), ""]
            continue
        lines += ["| Pair | Pose | mm3 | dist_mm | class | result |", "|---|---|---|---|---|---|"]
        for pose in POSES:
            pd = probes[pose]
            for key, errs in gates.pair_violations(pd, pose, T):
                if key in pd["pairs"]:
                    m3, dist = "%.3f" % pd["pairs"][key]["overlap_mm3"], "%.3f" % pd["pairs"][key]["min_dist"]
                elif key in pd["feature_pairs"] and pd["feature_pairs"][key].get("gap") is not None:
                    m3, dist = "-", "%.3f" % pd["feature_pairs"][key]["gap"]
                else:
                    m3, dist = "-", "nan"
                res = "pass" if not errs else "FAIL"
                totals["pairs"] += 1
                totals["fail"] += res == "FAIL"
                lines.append("| %s | %s | %s | %s | %s | %s |" % (key.replace("|", " / "), pose, m3, dist, gates.pair_class_letter(key, pose, T), res))
        lines.append("")
    # ------------------------------------------------------------- clamp range
    lo, hi = min(fam), max(fam)
    lines += ["## Clamp range (T4, T5)", "", "| Size | Pose | engaged_mm | min needed | slit_width_clamped_min | slit floor | nut_stop_travel_mm | one pitch | flange gap to rim | T4 | T5 |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    need_engaged = G("thread.min_engage_pitches") * G("thread.pitch")
    for d in (lo, hi):
        for pose in POSES:
            pd = load("pose_%s_%s" % (pose, tag(d)))
            if pd is None:
                continue
            ms = pd["measures"]
            eng = ms.get("engaged_mm")
            slit, trav = ms.get("slit_width_clamped_min"), ms.get("nut_stop_travel_mm")
            gap = pd["feature_pairs"].get("holder flange underside|receiver rim", {}).get("gap")
            t4 = "pass" if eng is not None and eng >= need_engaged else "FAIL"
            if pose == "R":
                t5 = "pass" if t4 == "pass" else "FAIL"
            else:
                t5 = "pass" if (slit is not None and slit > G("collet.min_slit_clamped") and trav is not None and trav >= G("thread.pitch")
                                and gap is not None and gap > 0 and t4 == "pass") else "FAIL"
            f = lambda v: "-" if v is None else "%.3f" % v
            lines.append("| %s | %s | %s | %.3f | %s | %.3f | %s | %.3f | %s | %s | %s |" % (
                tag(d), pose, f(eng), need_engaged, f(slit), G("collet.min_slit_clamped"), f(trav), G("thread.pitch"), f(gap), t4, t5))
    lines.append("")
    # ------------------------------------------------------------- wrong states
    lines += ["## Wrong states (WS1 to WS11)", "", "| WS | State | Pose | Fired | Expected | result |", "|---|---|---|---|---|---|"]
    for n in sorted(gates.WS_EXPECT):
        w = load("ws%d" % n)
        if w is None:
            lines.append("| WS%d | %s | - | no probe | %s | FAIL |" % (n, gates.WS_NAMES[n], ", ".join(sorted(gates.WS_EXPECT[n]))))
            continue
        fired = set(w["fired"])
        ok = bool(fired) and fired <= set(gates.GATES) and bool(fired & gates.WS_EXPECT[n])
        lines.append("| WS%d | %s | %s | %s | %s | %s |" % (n, gates.WS_NAMES[n], w["pose"], ", ".join(sorted(fired)) or "none",
                                                         ", ".join(sorted(gates.WS_EXPECT[n])), "pass" if ok else "FAIL"))
    z = load("ws0")
    if z is not None:
        lines.append("| zero control | unplanted R, Kd1, Kmax | nominal | %s | none | %s |" % (", ".join(z["fired"]) or "none", "pass" if not z["fired"] else "FAIL"))
    lines += ["", "Totals: %d pair rows, %d FAIL." % (totals["pairs"], totals["fail"]), ""]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("REPORT_OK rows=%d fail=%d" % (totals["pairs"], totals["fail"]))


if __name__ == "__main__":
    main()
